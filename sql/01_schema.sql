CREATE DATABASE IF NOT EXISTS supply_chain_intelligence;
USE supply_chain_intelligence;

CREATE TABLE IF NOT EXISTS clean_orders (
  order_id BIGINT,
  order_item_id BIGINT PRIMARY KEY,
  customer_id BIGINT,
  order_date DATETIME,
  shipping_date DATETIME,
  shipping_mode VARCHAR(50),
  market VARCHAR(100),
  region VARCHAR(150),
  country VARCHAR(150),
  state VARCHAR(150),
  city VARCHAR(150),
  customer_segment VARCHAR(80),
  category_name VARCHAR(150),
  department_name VARCHAR(150),
  product_name TEXT,
  order_status VARCHAR(80),
  actual_shipping_days DECIMAL(10,2),
  scheduled_shipping_days DECIMAL(10,2),
  late_delivery_risk TINYINT,
  sales DECIMAL(14,2),
  profit DECIMAL(14,2),
  order_item_total DECIMAL(14,2),
  quantity DECIMAL(10,2),
  discount DECIMAL(10,4),
  product_price DECIMAL(14,2),
  delivery_delay_days DECIMAL(10,2),
  sla_breach TINYINT,
  profit_margin_pct DECIMAL(10,4),
  month DATE,
  year INT,
  quarter VARCHAR(10),
  INDEX idx_order_date(order_date),
  INDEX idx_market(market),
  INDEX idx_region(region),
  INDEX idx_category(category_name),
  INDEX idx_shipping(shipping_mode)
);
